def format_facts(facts: List[Fact]) -> str:
    if not facts:
        return "（无检索结果）"
    lines = []
    for f in facts:
        lines.append(f"[{f.fact_id}]（{f.fact_type}｜型号：{f.product_model}｜来源：{f.source_title}）{f.content}")
    return "\n".join(lines)


def format_images(images: List[ImageAsset]) -> str:
    if not images:
        return "（无可用图片）"
    lines = []
    for img in images:
        lines.append(
            f"[{img.image_id}] 型号：{img.product_model}｜画面：{img.description}｜"
            f"文件：{img.file_name}｜来源：{img.source_page}｜建议用途：{img.suggested_use}"
        )
    return "\n".join(lines)


def format_task(task: Task) -> str:
    return json.dumps({
        "产品型号": task.product,
        "目标人群": task.target_audience,
        "使用场景": task.scenario,
        "发布平台": task.platform.value,
        "内容目标": task.content_goal,
        "特殊要求": task.special_requirements,
    }, ensure_ascii=False, indent=2)
